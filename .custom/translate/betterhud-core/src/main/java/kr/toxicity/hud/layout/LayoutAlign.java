package kr.toxicity.hud.layout;

/**
 * Horizontal text/image alignment within a HUD layout slot.
 */
public enum LayoutAlign {

    /** Align content to the left edge of its bounding box. */
    LEFT,

    /** Centre content within its bounding box. */
    CENTER,

    /** Align content to the right edge of its bounding box. */
    RIGHT
}
